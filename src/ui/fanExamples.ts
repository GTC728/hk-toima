import type { TileId } from '../engine'

/** 圖解用示範牌組（組與組之間留空）；唔係完整糊牌時只展示關鍵結構。 */
export type FanTileGroups = TileId[][]

function t(suit: string, n: number | string): TileId {
  return `${suit}-${n}` as TileId
}

function trip(id: TileId): TileId[] {
  return [id, id, id]
}

function pair(id: TileId): TileId[] {
  return [id, id]
}

function chi(suit: 'man' | 'pin' | 'sou', start: number): TileId[] {
  return [t(suit, start), t(suit, start + 1), t(suit, start + 2)]
}

function kong(id: TileId): TileId[] {
  return [id, id, id, id]
}

